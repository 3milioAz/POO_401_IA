package unidad2.practicas.practicasPoo;

public class OperacionMatematica {

    public static void main(String[] args) {

        // Declaración + asignación en una sola sentencia
        int producto = 5 * 11;

        // Declaracion
        int cociente;

        // Asignación
        // Expresion (20 / 5)
        cociente = 20 / 5;

        System.out.println("El producto de 5 x 11 es: " + producto);
        System.out.println("El cociente de 20/5 es: " + cociente);
    }
}